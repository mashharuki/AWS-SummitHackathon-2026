type Locale = "ja" | "en";

function detectInitialLanguage(): Locale {
  const stored = localStorage.getItem(STORAGE_KEY);
  if (stored === "ja" || stored === "en") {
    return stored;
  }
  return navigator.language.toLowerCase().startsWith("ja") ? "ja" : "en";
}

